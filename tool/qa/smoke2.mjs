import { open, shot, clickLabel, byLabel, report, sleep } from './harness.mjs';
const s = await open({ browser: 'chrome', device: 'desktop', url: 'http://localhost:8099/', theme: 'dark' });
console.log('menü düğmesi:', await byLabel(s, 'Menüyü aç veya kapat').count());
await clickLabel(s, 'Menüyü aç veya kapat'); await sleep(1500);
console.log(await shot(s, 'smoke_menu'));
await s.page.keyboard.press('Escape'); await sleep(1200);
await clickLabel(s, 'Açık temaya geç'); await sleep(1500);
console.log(await shot(s, 'smoke_light'));
console.log(report(s));
await s.close();
