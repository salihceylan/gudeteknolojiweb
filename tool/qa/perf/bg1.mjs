import { launch, ready, sleep, URL0 } from './util.mjs';
const s = await launch();
const { page, ctx } = s;
await page.goto(URL0, { waitUntil: 'load', timeout: 90000 });
await ready(page); await sleep(3000);
const cdp = await ctx.newCDPSession(page);
await cdp.send('Performance.enable');
const task = async () => Object.fromEntries((await cdp.send('Performance.getMetrics')).metrics.map((x) => [x.name, x.value])).TaskDuration;
const frames = () => page.evaluate(() => new Promise((res) => { let n = 0; const t0 = performance.now(); const f = () => { n++; if (performance.now() - t0 < 3000) requestAnimationFrame(f); else res(n); }; requestAnimationFrame(f); setTimeout(() => res(n + ' (timeout path)'), 3600); }));
let t0 = await task(); await sleep(4000); let t1 = await task();
console.log('visible: idle CPU task sec per 4s =', (t1 - t0).toFixed(2), 'vis=', await page.evaluate(() => document.visibilityState));
const p2 = await ctx.newPage(); await p2.goto('about:blank'); await p2.bringToFront(); await sleep(500);
console.log('after 2nd tab front: vis=', await page.evaluate(() => document.visibilityState));
t0 = await task(); await sleep(4000); t1 = await task();
console.log('hidden(?): CPU task sec per 4s =', (t1 - t0).toFixed(2));
await page.bringToFront(); await sleep(500);
console.log('back: vis=', await page.evaluate(() => document.visibilityState));
t0 = await task(); await sleep(4000); t1 = await task();
console.log('visible again: CPU task per 4s =', (t1 - t0).toFixed(2));
await s.close();
